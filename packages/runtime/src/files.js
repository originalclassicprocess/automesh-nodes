import { open, rename, mkdir, lstat, unlink } from 'node:fs/promises';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
import { setTimeout as pause } from 'node:timers/promises';

const renameWait = [10, 25, 50, 100, 200, 400];
// Windows can briefly hold a just-closed file (indexer/antivirus). Keep the
// atomic rename and fsync boundary: never delete the old destination or report
// success until rename succeeds. Permanent failures still fail closed.
export async function renameCommitted(source, destination, { platform = process.platform, move = rename, wait = pause } = {}) {
  for (let attempt = 0; ; attempt++) {
    try { await move(source, destination); return; }
    catch (error) {
      if (platform !== 'win32' || !['EPERM','EACCES','EBUSY'].includes(error.code) || attempt >= renameWait.length) throw error;
      await wait(renameWait[attempt]);
    }
  }
}

export async function privateDirectory(path) {
  await mkdir(path, { recursive: true, mode: 0o700 });
  const info = await lstat(path);
  if (!info.isDirectory() || info.isSymbolicLink()) throw new Error('unsafe_data_directory');
}

// Temp and destination are in the same directory. Ack only after fsync + rename.
// A leftover temp file is not considered committed on restart.
export async function writeAtomic(directory, name, value) {
  if (!/^[a-zA-Z0-9_.-]{1,128}$/.test(name) || name === '.' || name === '..') throw new Error('invalid_store_name');
  const temporary = join(directory, `.pending-${randomBytes(16).toString('hex')}`);
  const handle = await open(temporary, 'wx', 0o600);
  try { await handle.writeFile(JSON.stringify(value)); await handle.sync(); }
  finally { await handle.close(); }
  await renameCommitted(temporary, join(directory, name));
  await syncDirectory(directory);
}
export async function removeAtomic(directory, name) {
  // Names are generated by the store, never supplied as paths by a client.
  if (!/^(?:[a-f0-9]{32}(?:-[0-9]{1,4})?|[a-f0-9]{64})\.json$/.test(name)) throw new Error('invalid_store_name');
  try { await unlink(join(directory, name)); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await syncDirectory(directory);
}
async function syncDirectory(directory) {
  // Windows does not support opening directories for fsync.
  if (process.platform !== 'win32') {
    const directoryHandle = await open(directory, 'r');
    try { await directoryHandle.sync(); } finally { await directoryHandle.close(); }
  }
}
